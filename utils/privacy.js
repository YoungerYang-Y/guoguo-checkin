function hasAgreed() {
  try {
    return wx.getStorageSync(AGREE_KEY) === VERSION;
  } catch (e) {
    return false;
  }
}

function setAgreed() {
  try {
    wx.setStorageSync(AGREE_KEY, VERSION);
    return true;
  } catch (e) {
    return false;
  }
}

function revoke() {
  try {
    wx.removeStorageSync(AGREE_KEY);
    return true;
  } catch (e) {
    return false;
  }
}

